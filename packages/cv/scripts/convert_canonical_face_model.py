"""Convert MediaPipe's canonical face model to src/canonicalFaceModel.ts.

Inputs come from google-ai-edge/mediapipe at commit SOURCE_COMMIT, folder
mediapipe/modules/face_geometry/data:

    canonical_face_model.obj
    geometry_pipeline_metadata_landmarks.pbtxt

Download both into an empty folder, then run with an isolated interpreter:

    python3 -I scripts/convert_canonical_face_model.py <obj> <pbtxt> src/canonicalFaceModel.ts

The script refuses inputs whose SHA-256 differs from the pinned values and
checks that the pbtxt mesh matches the obj vertex positions.
"""

import hashlib
import re
import sys

SOURCE_COMMIT = "4ad67abd7093e064788f8b934a73ed3da67d57f8"
OBJ_SHA256 = "8bac80443397e113f41a8b565ea72c59390bc031d9defab289dba7bc0c54e618"
PBTXT_SHA256 = "55ca7c4c7bf195673b9d12a1b5d49d4b9c82b5ade8fed4b565496590866e359d"
VERTEX_COUNT = 468
PROCRUSTES_COUNT = 33
CM_TO_MM = 10.0

HEADER = """\
// Generated by scripts/convert_canonical_face_model.py; rerun it to change this file.
//
// Derived from MediaPipe face geometry data (canonical_face_model.obj and
// geometry_pipeline_metadata_landmarks.pbtxt), google-ai-edge/mediapipe commit
// {commit}.
// Copyright 2020 The MediaPipe Authors. Licensed under the Apache License,
// Version 2.0. See third_party/mediapipe/LICENSE.
//
// Changes from the source: keeps only the {count} Procrustes landmarks, converts
// centimetres to millimetres, and negates y and z (a 180 degree rotation about
// x) so a frontal, upright face has the identity rotation in the solver camera
// frame (x right, y down, z away from the camera). The origin is unchanged.

import type {{ Vec3 }} from './linalg.ts';

export interface CanonicalLandmark {{
  readonly landmarkIndex: number;
  readonly positionMm: Vec3;
  readonly procrustesWeight: number;
}}

export const CANONICAL_PROCRUSTES_LANDMARKS: readonly CanonicalLandmark[] = [
"""


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def read_obj_vertices(path):
    vertices = []
    with open(path) as f:
        for line in f:
            if line.startswith("v "):
                vertices.append(tuple(float(v) for v in line.split()[1:4]))
    return vertices


def read_pbtxt(path):
    with open(path) as f:
        text = f.read()
    basis = [
        (int(m.group(1)), float(m.group(2)))
        for m in re.finditer(r"procrustes_landmark_basis\s*\{\s*landmark_id:\s*(\d+)\s+weight:\s*([0-9.eE+-]+)\s*\}", text)
    ]
    buffer = [float(v) for v in re.findall(r"vertex_buffer:\s*([0-9.eE+-]+)", text)]
    return basis, buffer


def format_mm(value_cm, sign):
    value = round(sign * value_cm * CM_TO_MM, 5) + 0.0
    text = f"{value:.5f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    obj_path, pbtxt_path, out_path = argv[1:]
    for path, expected in ((obj_path, OBJ_SHA256), (pbtxt_path, PBTXT_SHA256)):
        actual = sha256(path)
        if actual != expected:
            sys.exit(f"{path}: SHA-256 {actual} does not match pinned {expected}")

    vertices = read_obj_vertices(obj_path)
    basis, buffer = read_pbtxt(pbtxt_path)
    if len(vertices) != VERTEX_COUNT:
        sys.exit(f"expected {VERTEX_COUNT} obj vertices, found {len(vertices)}")
    if len(basis) != PROCRUSTES_COUNT:
        sys.exit(f"expected {PROCRUSTES_COUNT} Procrustes landmarks, found {len(basis)}")
    # VERTEX_PT layout: x, y, z, u, v per vertex.
    if len(buffer) != VERTEX_COUNT * 5:
        sys.exit(f"unexpected pbtxt vertex buffer length {len(buffer)}")
    for i, vertex in enumerate(vertices):
        mesh = buffer[i * 5 : i * 5 + 3]
        if max(abs(a - b) for a, b in zip(vertex, mesh)) > 1e-6:
            sys.exit(f"obj and pbtxt disagree at vertex {i}")

    lines = [HEADER.format(commit=SOURCE_COMMIT, count=PROCRUSTES_COUNT)]
    for landmark_index, weight in basis:
        x, y, z = vertices[landmark_index]
        position = ", ".join((format_mm(x, 1), format_mm(y, -1), format_mm(z, -1)))
        lines.append(
            f"  {{ landmarkIndex: {landmark_index}, positionMm: [{position}], procrustesWeight: {weight!r} }},\n"
        )
    lines.append("];\n")
    with open(out_path, "w") as f:
        f.write("".join(lines))


if __name__ == "__main__":
    main(sys.argv)
